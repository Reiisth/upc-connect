import { spawn } from 'node:child_process';
import { loadLocalEnv } from './local-env.mjs';
import { localDevConfig } from './local-dev-config.mjs';
import { assertDevPortAvailable } from './local-dev-port.mjs';
loadLocalEnv();
if (process.argv.length > 3 || (process.argv[2] && process.argv[2] !== '--lan')) throw new Error('Use dev-local.mjs [--lan].');
const config = await localDevConfig(process.env, process.argv[2] === '--lan');
await assertDevPortAvailable(config.port);
console.log(`Local app: http://127.0.0.1:${config.port}`);
if (config.env.UPC_LOCAL_LAN_HOST) console.log(`LAN app: http://${config.env.UPC_LOCAL_LAN_HOST}:${config.port}`);
console.log(`Browser Supabase: ${config.env.NEXT_PUBLIC_SUPABASE_URL}`);
console.log(`Privileged Supabase: ${new URL(config.env.UPC_LOCAL_INTERNAL_SUPABASE_URL).origin}`);
const child = spawn(process.execPath, config.args, { env: config.env, stdio: 'inherit' });
child.on('error', error => { console.error(error.message); process.exitCode = 1; });
child.on('exit', code => { process.exitCode = code ?? 1; });
