type ConfigField = { field_key: string; is_builtin?: boolean; [key: string]: unknown };
const properties = ["label", "field_type", "field_group", "is_required", "is_visible", "placeholder", "options_source", "options"] as const;
export function isDefaultProfileConfiguration(fields: ConfigField[]) {
  const builtins = fields.filter(field => field.is_builtin);
  const defaults = PROFILE_FIELD_DEFAULTS.filter(field => isProfileDefinition({ ...field, is_builtin: true }));
  if (builtins.some(field => {
    const expected = defaults.find(item => item.field_key === field.field_key);
    return !expected || properties.some(key => JSON.stringify(field[key] ?? null) !== JSON.stringify(expected[key] ?? null));
  })) return false;
  for (const group of new Set(defaults.map(field => field.field_group))) {
    const actual = builtins.filter(field => field.field_group === group).sort((a,b) => Number(a.sort_order) - Number(b.sort_order)).map(field => field.field_key);
    const expected = defaults.filter(field => field.field_group === group && actual.includes(field.field_key)).sort((a,b) => a.sort_order - b.sort_order).map(field => field.field_key);
    if (JSON.stringify(actual) !== JSON.stringify(expected)) return false;
  }
  return true;
}
